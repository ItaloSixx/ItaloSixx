_ADV = 6  # 5 colunas + 1 de respiro


def text_w(s: str, px: int = 1) -> int:
    return max(0, len(s) * _ADV - 1) * px


def _missing(ch: str) -> list[str]:
    """Glifo ausente falha alto: melhor quebrar do que imprimir texto errado."""
    raise KeyError(f"glyph ausente no alfabeto: {ch!r}")


def text(s: str, x: float, y: float, px: int = 1, color: str = INK) -> str:
    """Escreve com o alfabeto autoral. (x, y) = canto superior esquerdo."""
    out = []
    cx = x
    for ch in s.upper():
        if ch == " ":
            cx += _ADV * px
            continue
        g = GLYPHS.get(ch) or _missing(ch)
        # junta células horizontais contíguas num só rect (menos nós no SVG)
        for row, bits in enumerate(g):
            run = 0
            for col in range(6):
                on = col < 5 and bits[col] == "1"
                if on:
                    run += 1
                elif run:
                    out.append(
                        f'<rect x="{cx + (col - run) * px:.1f}" y="{y + row * px:.1f}" '
                        f'width="{run * px:.1f}" height="{px}" fill="{color}"/>'
                    )
                    run = 0
        cx += _ADV * px
    return "".join(out)
